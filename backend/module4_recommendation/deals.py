def get_deals_for_deficiencies(top_deficiencies=None):
    """
    Returns verified deals matching user's top nutrient deficiencies.
    If no deficiencies specified, returns all top-rated supplement deals.
    """
    if not top_deficiencies:
        return ALL_SUPPLEMENT_DEALS

    # Normalize deficiency names
    normalized_defs = [d.strip().lower() for d in top_deficiencies]
    
    matched_deals = []
    for deal in ALL_SUPPLEMENT_DEALS:
        target = deal["target_deficiency"].lower()
        if any(nd in target or target in nd for nd in normalized_defs):
            matched_deals.append(deal)

    # If no specific matches found, return overall list
    return matched_deals if matched_deals else ALL_SUPPLEMENT_DEALS
